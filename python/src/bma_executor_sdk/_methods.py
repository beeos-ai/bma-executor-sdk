"""Typed protocol method descriptors (ADR 0012 §4.3); the instances are in
``bma_executor_sdk.methods`` (generated by tools/gen_methods.py)."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Generic, TypeVar

P = TypeVar("P")
R = TypeVar("R")

__all__ = ["Call", "Notification", "Request"]


@dataclass(frozen=True)
class Request(Generic[P, R]):
    """A harness-to-executor request with params ``P`` and result ``R``,
    served with ``client.on_request``."""

    method: str


@dataclass(frozen=True)
class Call(Generic[P, R]):
    """An executor-to-harness request with params ``P`` and result ``R``,
    sent with ``await client.call``."""

    method: str


@dataclass(frozen=True)
class Notification(Generic[P]):
    """An executor-to-harness notification with params ``P``, sent with
    ``await client.notify``."""

    method: str
