#!/usr/bin/env python3
"""Typed protocol methods for the Go and Python executor clients (ADR 0012 §4.3).

Reads the method table of the contract-generated Python module
(python/src/bma_executor_sdk/generated.py, written by BMA's
`make contract-sdk` from executor.openrpc.yaml) and writes one typed
descriptor per method a client may use itself:

- harness-to-executor requests a client serves (process.*, terminal.*,
  skill.install, workspace.backup; the others are served by the client's own
  tool, session, drain and agent handling),
- executor-to-harness requests and notifications a client sends.

TypeScript needs no output: generated/executor.ts already has
MethodParamsMap / MethodResultMap and the per-direction method unions.

    python3 tools/gen_methods.py          # write methods_gen.go and python/.../methods.py
    python3 tools/gen_methods.py --check  # fail when either is out of date
"""
from __future__ import annotations

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GO_OUT = ROOT / "methods_gen.go"
PY_OUT = ROOT / "python/src/bma_executor_sdk/methods.py"

# Served by the client itself: the tool, session and drain handlers and the
# agent runtime (ServeAgent / serve_agent).
SERVED = {
    "tool.call", "tool.cancel", "session.assign", "session.stop", "executor.drain",
    "turn.start", "turn.input", "turn.cancel", "session.close", "interaction.response",
}
# Sent by the client itself (registration, heartbeat, token refresh, close).
SENT = {"executor.register", "executor.heartbeat", "executor.token.refresh", "executor.close"}


def load_methods() -> list:
    spec = importlib.util.spec_from_file_location("_generated", ROOT / "python/src/bma_executor_sdk/generated.py")
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["_generated"] = module
    spec.loader.exec_module(module)
    return list(module.METHODS.values())


def pascal(method: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in method.replace(".", "_").split("_"))


def constant(method: str) -> str:
    return method.replace(".", "_").upper()


def groups(methods: list) -> tuple[list, list, list]:
    requests = [m for m in methods if m.direction == "harness-to-executor" and m.kind == "request" and m.name not in SERVED]
    calls = [m for m in methods if m.direction == "executor-to-harness" and m.kind == "request" and m.name not in SENT]
    notifications = [m for m in methods if m.direction == "executor-to-harness" and m.kind == "notification" and m.name not in SENT]
    return requests, calls, notifications


def render_go(methods: list) -> str:
    requests, calls, notifications = groups(methods)
    out = [
        "// Code generated by tools/gen_methods.py from the contract method table; DO NOT EDIT.",
        "",
        "package bmaexecutor",
        "",
    ]

    def block(var: str, doc: str, kind: str, items: list, typed) -> None:
        out.append(f"// {var} {doc}")
        out.append(f"var {var} = struct {{")
        for m in items:
            out.append(f"\t{pascal(m.name)} {kind}[{typed(m)}]")
        out.append("}{")
        for m in items:
            out.append(f"\t{pascal(m.name)}: {kind}[{typed(m)}]{{Method: \"{m.name}\"}},")
        out.append("}")
        out.append("")

    block("Requests", "are the harness-to-executor requests a client serves:\n// Requests.ProcessStart.Handle(client, fn).",
          "RequestMethod", requests, lambda m: f"{m.params_type}, {m.result_type}")
    block("Calls", "are the executor-to-harness requests a client sends:\n// Calls.SessionEvent.Call(ctx, client, params).",
          "CallMethod", calls, lambda m: f"{m.params_type}, {m.result_type}")
    block("Notifications", "are the executor-to-harness notifications a client sends:\n// Notifications.ToolProgress.Notify(ctx, client, params).",
          "NotificationMethod", notifications, lambda m: m.params_type)
    return "\n".join(out)


def render_py(methods: list) -> str:
    requests, calls, notifications = groups(methods)
    names = sorted({m.params_type for m in requests + calls + notifications}
                   | {m.result_type for m in requests + calls if m.result_type})
    out = [
        "# Code generated by tools/gen_methods.py from the contract method table; DO NOT EDIT.",
        '"""Typed protocol methods (ADR 0012 §4.3): ``client.on_request(methods.PROCESS_START, handler)``,',
        "``await client.call(methods.SESSION_EVENT, params)``, ``await client.notify(methods.TOOL_PROGRESS, params)``.\"\"\"",
        "",
        "from __future__ import annotations",
        "",
        "from ._methods import Call, Notification, Request",
        "from .generated import (",
    ]
    out += [f"    {n}," for n in names]
    out += [")", "", "__all__ = ["]
    out += [f'    "{constant(m.name)}",' for m in requests + calls + notifications]
    out += ["]", "", "# Harness-to-executor requests a client serves with on_request."]
    out += [f'{constant(m.name)}: Request[{m.params_type}, {m.result_type}] = Request("{m.name}")' for m in requests]
    out += ["", "# Executor-to-harness requests a client sends with call."]
    out += [f'{constant(m.name)}: Call[{m.params_type}, {m.result_type}] = Call("{m.name}")' for m in calls]
    out += ["", "# Executor-to-harness notifications a client sends with notify."]
    out += [f'{constant(m.name)}: Notification[{m.params_type}] = Notification("{m.name}")' for m in notifications]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    methods = load_methods()
    go = subprocess.run(["gofmt"], input=render_go(methods), capture_output=True, text=True, check=True).stdout
    files = {GO_OUT: go, PY_OUT: render_py(methods)}
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("gen_methods: out of date (run python3 tools/gen_methods.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in files.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
