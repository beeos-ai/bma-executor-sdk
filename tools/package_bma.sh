#!/usr/bin/env bash
# Builds the bma release assets of version X.Y.Z into DIR: one archive per
# platform (bma-<os>-<arch>.tar.gz holding the bma binary), the manifest
# install.sh verifies (bma-manifest.json: version and each archive's sha256),
# install.sh itself, and the Homebrew formula (bma.rb) of the same archives.
#   tools/package_bma.sh X.Y.Z DIR
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
version="$1" out="$2"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "version must be X.Y.Z" >&2; exit 1; }
mkdir -p "$out"
out="$(cd "$out" && pwd)"
sum() { (command -v sha256sum >/dev/null && sha256sum "$1" || shasum -a 256 "$1") | cut -d' ' -f1; }

declare -A sums
for platform in darwin/arm64 darwin/amd64 linux/arm64 linux/amd64; do
  os="${platform%/*}" arch="${platform#*/}"
  work="$(mktemp -d)"
  CGO_ENABLED=0 GOOS="$os" GOARCH="$arch" go build -trimpath -ldflags "-s -w -X main.version=$version" \
    -o "$work/bma" ./cmd/bma
  name="bma-$os-$arch.tar.gz"
  tar -C "$work" -czf "$out/$name" bma
  rm -rf "$work"
  sums[$name]="$(sum "$out/$name")"
done

{
  printf '{\n  "version": "%s",\n  "artifacts": {\n' "$version"
  first=1
  for name in bma-darwin-arm64.tar.gz bma-darwin-amd64.tar.gz bma-linux-arm64.tar.gz bma-linux-amd64.tar.gz; do
    [ "$first" = 1 ] || printf ',\n'
    first=0
    printf '    "%s": "%s"' "$name" "${sums[$name]}"
  done
  printf '\n  }\n}\n'
} > "$out/bma-manifest.json"

cp packaging/unix/install.sh "$out/install.sh"

url="https://github.com/beeos-ai/bma-executor-sdk/releases/download/v$version"
cat > "$out/bma.rb" <<EOF
# Generated by bma-executor-sdk tools/package_bma.sh for v$version.
class Bma < Formula
  desc "Connect this computer to BMA (BeeOS Managed Agents)"
  homepage "https://github.com/beeos-ai/bma-executor-sdk"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/bma-darwin-arm64.tar.gz"
      sha256 "${sums[bma-darwin-arm64.tar.gz]}"
    end
    on_intel do
      url "$url/bma-darwin-amd64.tar.gz"
      sha256 "${sums[bma-darwin-amd64.tar.gz]}"
    end
  end

  on_linux do
    on_arm do
      url "$url/bma-linux-arm64.tar.gz"
      sha256 "${sums[bma-linux-arm64.tar.gz]}"
    end
    on_intel do
      url "$url/bma-linux-amd64.tar.gz"
      sha256 "${sums[bma-linux-amd64.tar.gz]}"
    end
  end

  def install
    bin.install "bma"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/bma version")
  end
end
EOF
echo "bma $version assets in $out"
